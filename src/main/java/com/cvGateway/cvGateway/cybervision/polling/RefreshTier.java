package com.cvGateway.cvGateway.cybervision.polling;

/**
 * 갱신 주기 등급.
 *
 * <p>API 하나당 스케줄러 하나를 두면 스케줄러가 수십 개로 늘고 호출 시점도 제각각이 된다.
 * 대신 데이터가 실제로 얼마나 자주 바뀌는지에 따라 등급을 나누고, <b>등급마다 스케줄러 하나</b>가
 * 그 등급에 속한 항목을 한 번에 받아온다.
 *
 * <p>실제 주기는 {@code cyber-vision.polling.*} 설정으로 바꾼다. 아래 기본값은 데이터 성격에서
 * 뽑은 출발점이며, Center 의 캐시 갱신 주기를 실측한 뒤 조정하는 것을 전제로 한다.
 */
public enum RefreshTier {

    /**
     * 1분. 운영 이상을 빨리 알아야 하고 응답이 가벼운 것.
     *
     * <p>센서 연결 상태, 최근 이벤트.
     */
    FAST,

    /**
     * 5분. 대시보드 집계 지표.
     *
     * <p>Center 가 이 계열을 캐시해 두므로 더 자주 불러도 같은 값이 온다.
     */
    NORMAL,

    /**
     * 30분. 목록성 데이터.
     *
     * <p>취약점과 리스크는 엔진이 배치로 계산하므로 분 단위로 볼 이유가 없다.
     */
    SLOW,

    /**
     * 6시간. 구성 정보.
     *
     * <p>그룹 구조, 네트워크 정의, 프리셋, 버전은 사람이 바꾸기 전에는 그대로다.
     */
    RARE
}
